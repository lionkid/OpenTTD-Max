#!/usr/bin/env python3
"""Vehicle catalogue: docs/CATALOG.md with one thumbnail per artwork (docs/catalog/<art>.png), names in
English / Traditional Chinese / Japanese and the in-game numbers from data/*.csv and tools/balance.py.

    python3 tools/catalog.py
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import balance  # noqa: E402
from gallery import TAIL, compose, view_image  # noqa: E402
from gen_nml import EXTRA_TEXT, airport_tier, train_tiles  # noqa: E402

OUT = ROOT / "docs" / "catalog"
VIEW, ZOOM = 5, "2x"


def thumb(category: str, art: str) -> str:
    gfx = ROOT / "gfx" / category / art
    m = json.loads((gfx / "manifest.json").read_text())
    if category == "trains":
        parts = m["parts"]
        units = parts["head"].get("units") or 8
        sx, sy = (-16 * units // 8) * 2, (8 * units // 8) * 2
        seq = [view_image(gfx, parts["head"], ZOOM, VIEW), view_image(gfx, parts["mid"], ZOOM, VIEW),
               view_image(gfx, parts["head"], ZOOM, TAIL[VIEW])]
        items = sorted([(im, dx, dy, -k * sx, -k * sy) for k, (im, dx, dy) in enumerate(seq)], key=lambda it: it[4])
        img = compose(items)
    else:
        part = m["parts"].get("body") or next(iter(m["parts"].values()))
        img, _, _ = view_image(gfx, part, ZOOM, VIEW)
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / f"{art}.png"
    img.save(path, optimize=True)
    return f"catalog/{art}.png"


def main():
    lines = ["# Vehicle catalogue / 車種型錄 / 車両カタログ", "",
             "Generated by `tools/catalog.py` from `data/*.csv`. Prices in in-game pounds at default base costs, inflation off.",
             "Images: 2x zoom, south-west view (in game up to 4x).", ""]
    for category, title in (("aircraft", "Aircraft / 飛機 / 航空機"), ("trains", "Trains / 列車 / 列車")):
        rows = list(csv.DictReader(open(ROOT / "data" / f"{category}.csv", encoding="utf-8")))
        rows.sort(key=lambda r: r["intro_date"])
        lines += [f"## {title} ({len(rows)})", ""]
        if category == "aircraft":
            lines += ["| | Vehicle | Year | km/h | Capacity | Runway | Airports | Price | Running / yr |",
                      "|---|---|---|---|---|---|---|---|---|"]
        else:
            lines += ["| | Vehicle | Year | km/h | Cars × seats | Platform | Power | Price | Running / yr |",
                      "|---|---|---|---|---|---|---|---|---|"]
        done = {}
        for r in rows:
            art = r["art"]
            if art not in done:
                done[art] = thumb(category, art)
            name = f"**{r['name_en']}**<br>{r['name_zh_tw']}<br>{r['name_ja']}"
            year = r["intro_date"][:4]
            if category == "aircraft":
                cp, rp = balance.aircraft_props(r)
                cap = f"{float(r['payload_t']):.0f} t" if "freighter" in r["role"] else f"{r['pax']} pax"
                tier = airport_tier(r)
                airports = EXTRA_TEXT["english"]["tiers"][tier] + ("" if tier == "small" else " (large aircraft)")
                lines.append(f"| ![]({done[art]}) | {name} | {year} | {r['speed_kmh']} | {cap} | "
                             f"{int(r['runway_m']):,} m | {airports} | "
                             f"£{cp * balance.AIR_PRICE_UNIT:,.0f} | £{rp * balance.AIR_RUN_UNIT:,.0f} |")
            else:
                cp, rp = balance.train_props(r)
                lines.append(f"| ![]({done[art]}) | {name} | {year} | {r['speed_kmh']} | {r['cars']} × {r['pax_per_car']} | "
                             f"{train_tiles(r)} tiles | {int(r['power_kw']):,} kW | £{cp * balance.TRAIN_PRICE_UNIT:,.0f} | £{rp * balance.TRAIN_RUN_UNIT:,.0f} |")
        lines.append("")
    (ROOT / "docs" / "CATALOG.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote docs/CATALOG.md and {len(list(OUT.glob('*.png')))} thumbnails")


if __name__ == "__main__":
    main()
