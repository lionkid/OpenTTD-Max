#!/usr/bin/env python3
"""Turn a timeline game log (tools/ingame/run.py --ai-settings timeline=1 ...) into docs/TIMELINE.md and
docs/qa/timeline.png: when each OpenTTD-Max vehicle was actually on sale in game, against its real
introduction year.

    python3 tools/timeline_report.py build/qa_timeline/openttd.log
"""
import argparse
import csv
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def parse(log: Path):
    on_sale = defaultdict(set)
    counts = {}
    for line in log.read_text(errors="replace").splitlines():
        m = re.search(r"MAXTEST year (\d+) air (\d+) rail (\d+) orig_air (\d+) orig_rail (\d+) \| air: (.*)\| rail: (.*)$", line)
        if not m:
            continue
        y = int(m.group(1))
        counts[y] = tuple(int(m.group(i)) for i in range(2, 6))
        for group in (m.group(6), m.group(7)):
            for name in (n.strip() for n in group.split(";")):
                if name:
                    on_sale[name].add(y)
    return on_sale, counts


def rows():
    out = []
    for cat in ("aircraft", "trains"):
        for r in csv.DictReader(open(ROOT / "data" / f"{cat}.csv", encoding="utf-8")):
            out.append((cat, r))
    return out


def chart(entries, years, path: Path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import FancyBboxPatch

    surface, ink, ink2, grid, series, tick = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df", "#2a78d6", "#52514e"
    groups = [("Aircraft", [e for e in entries if e[0] == "aircraft"]), ("Trains", [e for e in entries if e[0] == "trains"])]
    heights = [len(g[1]) for g in groups]
    fig, axes = plt.subplots(1, 2, figsize=(15, 0.21 * max(heights) + 1.6), facecolor=surface)
    y0, y1 = min(years), max(years)
    for ax, (title, items) in zip(axes, groups):
        ax.set_facecolor(surface)
        items = sorted(items, key=lambda e: (e[2], e[1]))
        for i, (_, name, intro, first, last) in enumerate(items):
            y = len(items) - 1 - i
            if first is not None:
                width = (last + 1) - first
                ax.add_patch(FancyBboxPatch((first, y - 0.3), width, 0.6, boxstyle="round,pad=0,rounding_size=0.25",
                                            linewidth=0, facecolor=series, mutation_aspect=0.08))
            ax.plot([intro, intro], [y - 0.42, y + 0.42], color=tick, linewidth=1.5, solid_capstyle="butt")
        ax.set_yticks(range(len(items)))
        ax.set_yticklabels([e[1] for e in reversed(items)], fontsize=7.5, color=ink2)
        ax.set_xlim(y0, y1 + 1)
        ax.set_ylim(-0.8, len(items) - 0.2)
        ax.set_xticks(range(1950, y1 + 2, 10))
        ax.tick_params(axis="x", colors=ink2, labelsize=8, length=0)
        ax.tick_params(axis="y", length=0)
        ax.grid(axis="x", color=grid, linewidth=0.8)
        ax.set_axisbelow(True)
        for side in ("top", "right", "left", "bottom"):
            ax.spines[side].set_visible(False)
        ax.set_title(title, loc="left", fontsize=11, color=ink, fontweight="bold")
    fig.suptitle("OpenTTD-Max vehicles on sale in game, 1950-2050 (bar)  |  real introduction year (grey tick)",
                 x=0.01, ha="left", fontsize=10, color=ink2)
    fig.tight_layout(rect=(0, 0, 1, 0.97))
    fig.savefig(path, dpi=110, facecolor=surface)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("log")
    ap.add_argument("--md", default=str(ROOT / "docs" / "TIMELINE.md"))
    ap.add_argument("--png", default=str(ROOT / "docs" / "qa" / "timeline.png"))
    args = ap.parse_args()
    on_sale, counts = parse(Path(args.log))
    years = sorted(counts)
    entries, problems = [], []
    lines = ["# Timeline test (generated by tools/timeline_report.py)", "",
             f"One OpenTTD 15.3 game from {years[0]} to {years[-1]} at unlimited fast-forward, both NewGRFs loaded with",
             "default parameters. The test AI logged the buildable engines every January.", "",
             "OpenTTD delays every new engine by a random 0-1.4 years and then offers it to one company for a",
             "one-year exclusive preview, so with January sampling a vehicle shows up 1-3 years after its real",
             "introduction year (the purchase list still shows the real design year).", "",
             "![Vehicles on sale in game](qa/timeline.png)", "",
             "## On sale per decade", "", "| Year | OpenTTD-Max aircraft | OpenTTD-Max trains | Original aircraft | Original trains |",
             "|---|---|---|---|---|"]
    for y in years:
        if y % 10 == 0:
            a, r, oa, orr = counts[y]
            lines.append(f"| {y} | {a} | {r} | {oa} | {orr} |")
    lines += ["", "## Every vehicle", "", "| Vehicle | Type | Real introduction | First on sale | Last on sale |", "|---|---|---|---|---|"]
    for cat, r in rows():
        name = r["name_en"]
        intro = int(r["intro_date"][:4])
        y_, m_, d_ = (int(v) for v in r["intro_date"].split("-"))
        intro_frac = y_ + (m_ - 1) / 12 + (d_ - 1) / 365
        ys = sorted(on_sale.get(name, ()))
        first = ys[0] if ys else None
        last = ys[-1] if ys else None
        entries.append((cat, name, intro, first, last))
        if not ys:
            if intro < years[-1]:
                problems.append(f"{name}: never on sale although introduced in {intro}")
            shown = ("never", "–")
        else:
            gaps = [y for y in range(first, last + 1) if y not in ys]
            if gaps:
                problems.append(f"{name}: not on sale in {gaps}")
            # Random delay (<= 1.4 y) + exclusive preview (1 y) + January sampling (< 1 y).
            if first - intro_frac > 3.5:
                problems.append(f"{name}: first on sale {first}, introduced {r['intro_date']}")
            shown = (str(first), f"{last}+" if last == years[-1] else str(last))
        lines.append(f"| {name} | {'aircraft' if cat == 'aircraft' else 'train'} | {intro} | {shown[0]} | {shown[1]} |")
    lines += ["", "## Findings", ""]
    lines += [f"- {p}" for p in problems] if problems else ["- Every vehicle went on sale within 3.5 years of its real introduction date and stayed on sale without gaps."]
    first_air = min(y for y in years if counts[y][0] > 0)
    first_rail = min(y for y in years if counts[y][1] > 0)
    no_air = [y for y in years if counts[y][0] == 0 and y >= first_air]
    no_rail = [y for y in years if counts[y][1] == 0 and y >= first_rail]
    if no_air or no_rail:
        lines.append(f"- Years without any OpenTTD-Max aircraft after {first_air}: {no_air or 'none'}; trains after {first_rail}: {no_rail or 'none'}")
    else:
        lines.append(f"- From {first_air} (aircraft) and {first_rail} (trains) on, at least one OpenTTD-Max vehicle was on sale every year.")
    text = Path(args.log).read_text(errors="replace")
    grf_issues = [l for l in text.splitlines() if "[grf]" in l and re.search(r"error|warning|invalid|unknown", l, re.I)
                  and "is missing" not in l]
    if grf_issues:
        problems.extend(grf_issues[:10])
        lines.append(f"- NewGRF messages in the log: {len(grf_issues)} (first ones listed above)")
    else:
        lines.append("- No NewGRF errors or warnings in the game log.")
    expected = list(range(years[0], years[-1] + 1))
    if years == expected:
        lines.append(f"- The game logged every year from {years[0]} to {years[-1]}: no crash or stall.")
    else:
        missing = sorted(set(expected) - set(years))
        problems.append(f"years missing from the log: {missing}")
        lines.append(f"- Years missing from the log: {missing}")
    Path(args.md).write_text("\n".join(lines) + "\n", encoding="utf-8")
    chart(entries, years, Path(args.png))
    print(f"wrote {args.md} and {args.png}; {len(problems)} finding(s)")
    for p in problems:
        print("  " + p)


if __name__ == "__main__":
    main()
